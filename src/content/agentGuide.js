export function globalAgentPrompt() {
  return '# 心鉴 / Sym Gen · 心理健康咨询与陪伴指南\n\n' +
    '请从现在起用温和、具体、平视的中文与我交流。我可以在这里谈困扰、了解精神疾病与治疗信息，或整理就医和复诊问题。先回应我已经提出的问题；还没有具体问题时，简短邀请我从愿意说的地方开始。\n\n' +
    '## 在这个聊天中直接使用\n' + independentSupportRules.map(text => `- ${text}`).join('\n') + '\n\n' +
    communicationPrompt() + '\n\n' + regionalPrompt() + '\n\n' +
    '## 讲解与行为要求\n' + agentBehaviourRules.map(text => `- ${text}`).join('\n') +
    `\n\n指南版本：${agentGuideVersion}\n`;
}

export function moduleAgentPrompt(id) {
  const module = agentModules.find(module => module.id === id);
  if (!module) throw new Error(`Unknown Agent module: ${id}`);
  return globalAgentPrompt() + `\n## 当前模块：${module.title}\n以下是这个主题的补充要求；话题转向个人困扰或其他主题时，继续按全局指南回应，不要求回到网站或固定模块。\n` + module.task.map(text => `- ${text}`).join('\n') + '\n';
}
